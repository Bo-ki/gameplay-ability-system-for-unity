        private static string ResolveProjectPath(string projectRoot, string path)
        {
            if (string.IsNullOrWhiteSpace(path))
                return projectRoot;

            return Path.GetFullPath(Path.IsPathRooted(path)
                ? path
                : Path.Combine(projectRoot, path));
        }

        private static void EnsureUnityMeta(string path)
        {
            var metaPath = path + ".meta";
            if (File.Exists(metaPath))
                return;

            File.WriteAllText(metaPath, "fileFormatVersion: 2\n" + $"guid: {CreateGuid()}\n");
        }

        private static string CreateGuid()
        {
            return Guid.NewGuid().ToString("N");
        }

        private static string IntArrayLiteral(IReadOnlyList<int> values)
        {
            return values == null || values.Count == 0
                ? "Array.Empty<int>()"
                : "new[] { " + string.Join(", ", values) + " }";
        }

        private static string FloatArrayLiteral(IReadOnlyList<float> values)
        {
            return values == null || values.Count == 0
                ? "Array.Empty<float>()"
                : "new[] { " + string.Join(", ", values.Select(FloatLiteral)) + " }";
        }

        private static string FloatLiteral(float value)
        {
            if (float.IsNaN(value))
                return "float.NaN";
            if (float.IsPositiveInfinity(value))
                return "float.PositiveInfinity";
            if (float.IsNegativeInfinity(value))
                return "float.NegativeInfinity";

            return value.ToString("R", CultureInfo.InvariantCulture) + "f";
        }

        private static string BoolLiteral(bool value)
        {
            return value ? "true" : "false";
        }

        private static string StringLiteral(string value)
        {
            if (value == null)
                return "string.Empty";

            return "\"" + value
                .Replace("\\", "\\\\")
                .Replace("\"", "\\\"")
                .Replace("\r", "\\r")
                .Replace("\n", "\\n") + "\"";
        }

