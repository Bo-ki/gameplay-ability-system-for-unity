            private ModifierRowModel BuildModifierRow(JToken row)
            {
                return new ModifierRowModel
                {
                    AttributeSetCode = Int(row?["AttrSet"]),
                    AttributeCode = Int(row?["Attribute"]),
                    Operation = Int(row?["Operation"]),
                    Magnitude = Float(row?["Magnitude"]),
                };
            }

            private TimelineDefinitionRowModel BuildTimelineRow(JToken row)
            {
                var effects = new List<int>();
                var targetCatcherName = string.Empty;
                foreach (var track in Array(row["Tracks"]))
                {
                    foreach (var clip in Array(track["ActionClips"]))
                    {
                        var action = clip["Action"];
                        if (String(action?["$type"]) != "ApplyEffects")
                            continue;

                        var param = action["Param"];
                        effects.AddRange(PositiveInts(param?["IDs"]));
                        if (string.IsNullOrEmpty(targetCatcherName))
                            targetCatcherName = String(param?["TargetCatcher"]?["$type"]);
                    }
                }

                return new TimelineDefinitionRowModel
                {
                    TimelineId = Int(row["ID"]),
                    GameplayEffectCode = effects.Count > 0 ? effects[0] : 0,
                    SecondaryGameplayEffectCode = effects.Count > 1 ? effects[1] : 0,
                    TargetCatcherName = targetCatcherName,
                };
            }

            private JArray ReadArray(string fileName)
            {
                var path = Path.Combine(m_projectRoot, m_settings.LubanDataOutputPath, fileName);
                if (!File.Exists(path))
                    throw new FileNotFoundException($"Luban JSON table is missing: {path}", path);

                var token = JToken.Parse(File.ReadAllText(path));
                if (token is JArray array)
                    return array;

                throw new InvalidDataException($"Luban JSON table root must be an array: {path}");
            }

            private static JArray Array(JToken token)
            {
                return token as JArray ?? new JArray();
            }

            private static int Int(JToken token)
            {
                return token == null || token.Type == JTokenType.Null ? 0 : token.Value<int>();
            }

            private static float Float(JToken token)
            {
                return token == null || token.Type == JTokenType.Null ? 0f : token.Value<float>();
            }

            private static bool Bool(JToken token)
            {
                return token != null && token.Type != JTokenType.Null && token.Value<bool>();
            }

            private static string String(JToken token)
            {
                return token == null || token.Type == JTokenType.Null ? string.Empty : token.Value<string>() ?? string.Empty;
            }

            private static int FirstPositive(JToken token)
            {
                var values = PositiveInts(token);
                return values.Length > 0 ? values[0] : 0;
            }

            private static TagRequirementRowModel ParseTagRequirement(JToken token)
            {
                if (token == null || token.Type == JTokenType.Null)
                    return TagRequirementRowModel.Empty;

                if (token is JArray)
                    return new TagRequirementRowModel(PositiveInts(token), System.Array.Empty<int>(), System.Array.Empty<int>());

                return new TagRequirementRowModel(
                    PositiveInts(token["All"]),
                    PositiveInts(token["Any"]),
                    PositiveInts(token["None"]));
            }

            private static int FirstRequirementTag(JToken token)
            {
                if (token == null || token.Type == JTokenType.Null)
                    return 0;

                var all = FirstPositive(token["All"]);
                if (all > 0)
                    return all;

                var any = FirstPositive(token["Any"]);
                return any > 0 ? any : 0;
            }

            private static int[] PositiveInts(JToken token)
            {
                if (token is not JArray array)
                    return System.Array.Empty<int>();

                return array
                    .Select(Int)
                    .Where(value => value > 0)
                    .ToArray();
            }

            private static string ParentTagName(string tagName)
            {
                if (string.IsNullOrWhiteSpace(tagName))
                    return string.Empty;

                var index = tagName.LastIndexOf('.');
                return index > 0 ? tagName.Substring(0, index) : string.Empty;
            }

            private static int StableHash(string value)
            {
                if (string.IsNullOrWhiteSpace(value))
                    return 0;

                unchecked
                {
                    var hash = (uint)2166136261;
                    for (var i = 0; i < value.Length; i++)
                    {
                        hash ^= value[i];
                        hash *= 16777619;
                    }

                    return (int)hash;
                }
            }
        }

