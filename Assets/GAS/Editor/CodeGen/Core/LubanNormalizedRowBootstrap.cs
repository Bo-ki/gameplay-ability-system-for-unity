            public AbilityDefinitionRowModel[] CreateAbilityRows(IReadOnlyList<TimelineDefinitionRowModel> timelineRows)
            {
                var timelines = timelineRows.ToDictionary(row => row.TimelineId, row => row);
                return ReadArray(AbilityJson)
                    .Select(row => BuildAbilityRow(row, timelines))
                    .Where(row => row.AbilityCode > 0)
                    .OrderBy(row => row.AbilityCode)
                    .ToArray();
            }

            public GameplayEffectDefinitionRowModel[] CreateGameplayEffectRows()
            {
                return ReadArray(GameplayEffectJson)
                    .Select(BuildGameplayEffectRow)
                    .Where(row => row.GameplayEffectCode > 0)
                    .OrderBy(row => row.GameplayEffectCode)
                    .ToArray();
            }

            public AttributeSetDefinitionRowModel[] CreateAttributeSetRows()
            {
                return ReadArray(AttributeSetJson)
                    .Select(row => new AttributeSetDefinitionRowModel
                    {
                        AttributeSetCode = Int(row["ID"]),
                    })
                    .Where(row => row.AttributeSetCode > 0)
                    .OrderBy(row => row.AttributeSetCode)
                    .ToArray();
            }

            public AttributeDefinitionRowModel[] CreateAttributeRows()
            {
                var result = new List<AttributeDefinitionRowModel>();
                foreach (var attrSet in ReadArray(AttributeSetJson))
                {
                    var attrSetCode = Int(attrSet["ID"]);
                    if (attrSetCode <= 0)
                        continue;

                    foreach (var attribute in Array(attrSet["Attribute"]))
                    {
                        var attributeCode = Int(attribute["ID"]);
                        if (attributeCode <= 0)
                            continue;

                        result.Add(new AttributeDefinitionRowModel
                        {
                            AttributeSetCode = attrSetCode,
                            AttributeCode = attributeCode,
                            InitialValue = Float(attribute["InitValue"]),
                            IsClampMin = Bool(attribute["UseMinValue"]),
                            IsClampMax = Bool(attribute["UseMaxValue"]),
                            MinValue = Float(attribute["MinValue"]),
                            MaxValue = Float(attribute["MaxValue"]),
                        });
                    }
                }

                return result
                    .OrderBy(row => row.AttributeSetCode)
                    .ThenBy(row => row.AttributeCode)
                    .ToArray();
            }

            public GameplayTagDefinitionRowModel[] CreateGameplayTagRows()
            {
                var rows = ReadArray(GameplayTagJson)
                    .Select(row => new
                    {
                        Code = Int(row["id"]),
                        Name = String(row["Name"]),
                    })
                    .Where(row => row.Code > 0)
                    .ToArray();
                var codeByName = rows
                    .GroupBy(row => row.Name ?? string.Empty)
                    .ToDictionary(group => group.Key, group => group.First().Code);
                var childrenByCode = new Dictionary<int, List<int>>();
                var parentByCode = new Dictionary<int, List<int>>();

                foreach (var row in rows)
                {
                    var parentName = ParentTagName(row.Name);
                    if (string.IsNullOrEmpty(parentName) || !codeByName.TryGetValue(parentName, out var parentCode))
                        continue;

                    if (!childrenByCode.TryGetValue(parentCode, out var children))
                    {
                        children = new List<int>();
                        childrenByCode[parentCode] = children;
                    }

                    if (!parentByCode.TryGetValue(row.Code, out var parents))
                    {
                        parents = new List<int>();
                        parentByCode[row.Code] = parents;
                    }

                    children.Add(row.Code);
                    parents.Add(parentCode);
                }

                return rows
                    .OrderBy(row => row.Code)
                    .Select(row => new GameplayTagDefinitionRowModel
                    {
                        GameplayTagCode = row.Code,
                        ParentCodes = parentByCode.TryGetValue(row.Code, out var parents) ? parents.OrderBy(code => code).ToArray() : System.Array.Empty<int>(),
                        ChildCodes = childrenByCode.TryGetValue(row.Code, out var children) ? children.OrderBy(code => code).ToArray() : System.Array.Empty<int>(),
                    })
                    .ToArray();
            }

