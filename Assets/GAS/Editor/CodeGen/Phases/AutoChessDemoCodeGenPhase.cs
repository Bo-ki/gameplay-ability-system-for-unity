        /// </summary>
        public override void Execute(GasCodeGenContext context, GasCodeGenManifest manifest)
        {
            var path = GetOutputPath(context, OutputFileNames[0]);
            Directory.CreateDirectory(Path.GetDirectoryName(path));
            AddRuntimeManifest(manifest, PhaseName, path);
            var model = AutoChessDemoConfigModel.FromLubanJson(context);
            var catalogPlan = CatalogEmissionPlan.Create(model.RuntimeCatalog);

            using var stream = new StreamWriter(path);
            using var writer = new IndentedWriter(stream);
            WriteAutoChessHeader(writer);
            writer.WriteLine("namespace GAS.AutoChessDemo");
            writer.WriteLine("{");
            writer.Indent++;
            WriteScenarioProfile(writer);
            writer.WriteLine();
            WriteGeneratedUnitSpawnPlan(writer);
            writer.WriteLine();
            WriteGeneratedDefinitionCatalog(writer, catalogPlan);
            writer.WriteLine();
            WriteGeneratedConfig(writer, model);
            writer.Indent--;
            writer.WriteLine("}");
            EnsureUnityMeta(path);
        }

