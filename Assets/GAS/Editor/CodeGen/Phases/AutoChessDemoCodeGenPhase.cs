        /// <summary>
        /// 把已校验模型编译成 generated flat arrays 与 per-definition ranges。
        /// </summary>
        private sealed class CatalogEmissionPlan
        {
            private CatalogEmissionPlan(AutoChessRuntimeV1CatalogModel model)
            {
                Model = model;
            }

            public AutoChessRuntimeV1CatalogModel Model { get; }
            public EffectEmissionPlan[] Effects { get; private set; }
            public List<CaptureEmissionPlan> Captures { get; } = new List<CaptureEmissionPlan>();
            public List<ModifierEmissionPlan> Modifiers { get; } = new List<ModifierEmissionPlan>();
            public List<CueEmissionPlan> Cues { get; } = new List<CueEmissionPlan>();
            public List<ValueViewEmissionPlan> ValueViews { get; } = new List<ValueViewEmissionPlan>();
            public List<EvaluatorEmissionPlan> Evaluators { get; } = new List<EvaluatorEmissionPlan>();

            /// <summary>
            /// 为每个 Effect 编译唯一 modifier/evaluator/cue 片段。
            /// </summary>
            public static CatalogEmissionPlan Create(AutoChessRuntimeV1CatalogModel model)
            {
                var plan = new CatalogEmissionPlan(model ?? throw new ArgumentNullException(nameof(model)));
                var effectsById = model.Effects.ToDictionary(row => row.GameplayEffectCode);
                var effectPlans = new List<EffectEmissionPlan>(model.Effects.Length);
                for (var index = 0; index < model.Effects.Length; index++)
                    effectPlans.Add(plan.CompileEffect(model.Effects[index], effectsById, index));
                plan.Effects = effectPlans.ToArray();
                return plan;
            }

            /// <summary>
            /// 编译单个 Effect，并记录所有 flat array 起点与数量。
            /// </summary>
            private EffectEmissionPlan CompileEffect(
                in AutoChessGameplayEffectRow effect,
                IReadOnlyDictionary<int, AutoChessGameplayEffectRow> effectsById,
                int effectIndex)
            {
                var captureStart = Captures.Count;
                var modifierStart = Modifiers.Count;
                var evaluatorStart = Evaluators.Count;
                var valueViewStart = ValueViews.Count;
                if (effect.Evaluator.Kind == 1)
                    CompileMissingHealthEvaluator(in effect);
                else if (effect.Evaluator.Kind == 2)
                    CompileAttackStackCountEvaluator(in effect);
                else
                    CompileFixedModifier(in effect, effectsById);
                var cueStart = Cues.Count;
                CompileCues(in effect);
                return new EffectEmissionPlan(
                    effect,
                    effect.Evaluator.Kind == 1 ? "InstantExecution" : effect.Duration.IsDefined ? "Duration" : "Instant",
                    captureStart,
                    Captures.Count - captureStart,
                    modifierStart,
                    Modifiers.Count - modifierStart,
                    evaluatorStart,
                    Evaluators.Count - evaluatorStart,
                    valueViewStart,
                    ValueViews.Count - valueViewStart,
                    cueStart,
                    Cues.Count - cueStart,
                    effectIndex,
                    effectIndex * 3,
                    effect.Evaluator.Kind == 1
                        ? "GasAttributeValueViewMask.Base | GasAttributeValueViewMask.Current | GasAttributeValueViewMask.DefinitionMaxValue"
                        : "GasAttributeValueViewMask.None");
            }

            /// <summary>
            /// 编译普通 Modifier；period root 会直接展开其唯一 child modifier。
            /// </summary>
            private void CompileFixedModifier(
                in AutoChessGameplayEffectRow effect,
                IReadOnlyDictionary<int, AutoChessGameplayEffectRow> effectsById)
            {
                var modifiers = effect.Modifiers;
                if (modifiers.Length == 0 && effect.Period.IsDefined)
                {
                    modifiers = effect.Period.EffectCodes
                        .SelectMany(id => effectsById[id].Modifiers)
                        .ToArray();
                }
                if (modifiers.Length != 1)
                    throw new InvalidDataException($"[AutoChessCatalog] Effect {effect.GameplayEffectCode} must compile to exactly one modifier.");
                var modifier = modifiers[0];
                var evaluatorStart = Evaluators.Count;
                var magnitude = modifier.Operation == 3 ? -modifier.Magnitude : modifier.Magnitude;
                Evaluators.Add(new EvaluatorEmissionPlan("PushConstant", 0, magnitude));
                Modifiers.Add(new ModifierEmissionPlan(
                    ResolveAttributeLayoutIndex(modifier.AttributeSetCode, modifier.AttributeCode),
                    ModifierOperation(modifier.Operation),
                    evaluatorStart,
                    1,
                    Captures.Count,
                    0));
            }

            /// <summary>
            /// 编译 TargetMissingHealth 为 3 个 ValueView 与 13 条 postfix 指令。
            /// </summary>
            private void CompileMissingHealthEvaluator(in AutoChessGameplayEffectRow effect)
            {
                var evaluator = effect.Evaluator;
                var layoutIndex = ResolveAttributeLayoutIndex(
                    evaluator.AttributeSetCode,
                    evaluator.AttributeCode);
                ValueViews.Add(new ValueViewEmissionPlan(layoutIndex, "Base"));
                ValueViews.Add(new ValueViewEmissionPlan(layoutIndex, "Current"));
                ValueViews.Add(new ValueViewEmissionPlan(layoutIndex, "DefinitionMaxValue"));
                var evaluatorStart = Evaluators.Count;
                AddInstruction("PushValueView", 2);
                AddInstruction("PushValueView", 0);
                AddInstruction("Subtract");
                AddConstant(0f);
                AddInstruction("Maximum");
                AddConstant(evaluator.Coefficient);
                AddInstruction("Multiply");
                AddConstant(evaluator.BaseValue);
                AddInstruction("Add");
                AddConstant(evaluator.Minimum);
                AddConstant(evaluator.Maximum);
                AddInstruction("Clamp");
                AddInstruction("Negate");
                Modifiers.Add(new ModifierEmissionPlan(
                    layoutIndex,
                    "Add",
                    evaluatorStart,
                    13,
                    Captures.Count,
                    0));
            }

            /// <summary>
            /// 编译 Source Attack Snapshot × coefficient × current stack count 的 period 伤害公式。
            /// </summary>
            private void CompileAttackStackCountEvaluator(in AutoChessGameplayEffectRow effect)
            {
                var evaluator = effect.Evaluator;
                var inputLayoutIndex = ResolveAttributeLayoutIndex(
                    evaluator.AttributeSetCode,
                    evaluator.AttributeCode);
                var modifier = effect.Modifiers[0];
                var outputLayoutIndex = ResolveAttributeLayoutIndex(
                    modifier.AttributeSetCode,
                    modifier.AttributeCode);
                var captureStart = Captures.Count;
                Captures.Add(new CaptureEmissionPlan(0, inputLayoutIndex));
                var evaluatorStart = Evaluators.Count;
                AddInstruction("PushCapture");
                AddConstant(evaluator.Coefficient);
                AddInstruction("Multiply");
                AddInstruction("PushStackCount");
                AddInstruction("Multiply");
                AddInstruction("Negate");
                Modifiers.Add(new ModifierEmissionPlan(
                    outputLayoutIndex,
                    "Add",
                    evaluatorStart,
                    6,
                    captureStart,
                    1));
            }

            /// <summary>
            /// 合并同一 Cue ID 的阶段并生成 definition-local ordinal。
            /// </summary>
            private void CompileCues(in AutoChessGameplayEffectRow effect)
            {
                var flagsByCue = new Dictionary<int, int>();
                AddCueFlags(flagsByCue, effect.CueOnApply, effect.Duration.IsDefined ? 1 : 4);
                AddCueFlags(flagsByCue, effect.CueOnTick, 2);
                AddCueFlags(flagsByCue, effect.CueOnAdd, 1);
                AddCueFlags(flagsByCue, effect.CueOnActivate, 1);
                AddCueFlags(flagsByCue, effect.CueOnRemove, 8);
                AddCueFlags(flagsByCue, effect.CueOnDeactivate, 8);
                var ordinal = 0;
                foreach (var pair in flagsByCue.OrderBy(pair => pair.Key))
                {
                    Cues.Add(new CueEmissionPlan(pair.Key, ordinal, pair.Value));
                    ordinal++;
                }
            }

            /// <summary>
            /// 合并一组 Cue ID 的阶段位。
            /// </summary>
            private static void AddCueFlags(
                IDictionary<int, int> flagsByCue,
                IEnumerable<int> cueIds,
                int flags)
            {
                foreach (var cueId in cueIds)
                {
                    flagsByCue.TryGetValue(cueId, out var existing);
                    flagsByCue[cueId] = existing | flags;
                }
            }

            /// <summary>
            /// 解析 AttributeSet+Attribute 到 generated dense layout index。
            /// </summary>
            private int ResolveAttributeLayoutIndex(int attributeSetCode, int attributeCode)
            {
                for (var index = 0; index < Model.Attributes.Length; index++)
                {
                    var attribute = Model.Attributes[index];
                    if (attribute.AttributeSetCode == attributeSetCode && attribute.AttributeCode == attributeCode)
                        return index;
                }
                throw new InvalidDataException($"[AutoChessCatalog] Unknown attribute {attributeSetCode}:{attributeCode}.");
            }

            /// <summary>
            /// 追加一条不带常量的 evaluator 指令。
            /// </summary>
            private void AddInstruction(string opcode, int operandIndex = 0)
            {
                Evaluators.Add(new EvaluatorEmissionPlan(opcode, operandIndex, 0f));
            }

            /// <summary>
            /// 追加一条 PushConstant evaluator 指令。
            /// </summary>
            private void AddConstant(float value)
            {
                Evaluators.Add(new EvaluatorEmissionPlan("PushConstant", 0, value));
            }

            /// <summary>
            /// 将 Luban Modifier operation 映射到 Runtime v1 闭集名称。
            /// </summary>
            private static string ModifierOperation(int operation)
            {
                return operation switch
                {
                    0 => "Add",
                    1 => "Multiply",
                    2 => "Override",
                    3 => "Add",
                    4 => "Divide",
                    _ => throw new InvalidDataException($"[AutoChessCatalog] Unsupported modifier operation: {operation}"),
                };
            }
        }

